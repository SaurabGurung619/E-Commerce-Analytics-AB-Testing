-- How many users were assigned to Group A and Group B?
select  experiment_group, count(*) as Total_Users from users
group by experiment_group
order by Total_Users desc;

-- What is the purchase conversion rate for Group A versus Group B?

SELECT
    experiment_group,
    COUNT(*) AS total_users,
    SUM(converted) AS total_purchases,
    COUNT(*) - SUM(converted) AS non_purchasers,
    ROUND(
        SUM(converted) * 100.0 / COUNT(*),
        2
    ) AS conversion_rate_pct
FROM users
GROUP BY experiment_group
ORDER BY experiment_group;

-- What is the absolute and relative conversion uplift of Group B compared with Group A?

WITH group_metrics AS (
    SELECT
        experiment_group,
        COUNT(*) AS total_users,
        SUM(converted) AS total_purchases
    FROM users
    GROUP BY experiment_group
),
conversion_rates AS (
    SELECT
        MAX(
            CASE WHEN experiment_group = 'A'
            THEN 100.0 * total_purchases / total_users
            END
        ) AS control_rate,
        MAX(
            CASE WHEN experiment_group = 'B'
            THEN 100.0 * total_purchases / total_users
            END
        ) AS treatment_rate
    FROM group_metrics
)
SELECT
    ROUND(control_rate, 2) AS control_rate_pct,
    ROUND(treatment_rate, 2) AS treatment_rate_pct,
    ROUND(
        treatment_rate - control_rate, 2
    ) AS absolute_uplift_pp,
    ROUND(
        100.0 * (treatment_rate - control_rate)
        / NULLIF(control_rate, 0), 2
    ) AS relative_uplift_pct
FROM conversion_rates;

-- Which checkout page generates higher total revenue and revenue per user?

SELECT
    experiment_group,
    COUNT(*) AS total_users,
    SUM(converted) AS total_purchases,
    ROUND(SUM(revenue), 2) AS total_revenue,
    ROUND(AVG(revenue), 2) AS revenue_per_user,
    ROUND(
        SUM(revenue) / NULLIF(SUM(converted), 0),
        2
    ) AS average_order_value
FROM users
GROUP BY experiment_group
ORDER BY experiment_group;

-- Which device type has the highest purchase conversion rate in Group A and Group B?

SELECT
    experiment_group,
    device_type,
    COUNT(*) AS total_users,
    SUM(converted) AS total_purchases,
    ROUND(
        100.0 * SUM(converted) / COUNT(*),
        2
    ) AS conversion_rate_pct
FROM users
GROUP BY
    experiment_group,
    device_type
ORDER BY
    device_type,
    experiment_group;

-- Which traffic source has the highest purchase conversion rate in Group A and Group B?

SELECT
    traffic_source,
    experiment_group,
    COUNT(*) AS total_users,
    SUM(converted) AS total_purchases,
    ROUND(
        100.0 * SUM(converted) / COUNT(*),
        2
    ) AS conversion_rate_pct
FROM users
GROUP BY
    traffic_source,
    experiment_group
ORDER BY
    traffic_source,
    conversion_rate_pct DESC;

-- How many users are from each country?
SELECT
    country,
    COUNT(*) AS total_users
FROM users
GROUP BY country
ORDER BY total_users DESC;

-- How many users purchased and how many did not purchase?
SELECT
    CASE
        WHEN converted = 1 THEN 'Purchased'
        WHEN converted = 0 THEN 'Not Purchased'
        ELSE 'Unknown'
    END AS purchase_status,
    COUNT(*) AS total_users
FROM users
GROUP BY purchase_status;

-- What is the total revenue generated by each experiment group?

SELECT
    experiment_group,
    ROUND(SUM(revenue), 2) AS total_revenue
FROM users
GROUP BY experiment_group
ORDER BY total_revenue DESC;

-- Which experiment group has a higher average checkout completion time among users who purchased?
SELECT
    experiment_group,
    ROUND(AVG(checkout_time_sec), 2)
        AS avg_checkout_time_sec
FROM users
WHERE converted = 1
GROUP BY experiment_group
ORDER BY avg_checkout_time_sec ASC;
